"""brain_lib.py - vault-maintenance library + CLI for the brain LLM-Wiki Obsidian vault.

INERT until called. The brain-* skills import and call:
    rebuild_index(vault)   -> rewrite vault/index.md,  return page count
    rebuild_mustknow(vault) -> rewrite each root's MUSTKNOW.md, return line count
    find_pages(vault, query) -> ranked matches, searched on demand
    append_log(vault, op, detail, private=False) -> prepend an entry to the first
        configured root's log.md, or to the privateVault log.md with private=True

Run via uv, never pip or a bare venv:
    uv run brain_lib.py rebuild [vault]
    uv run brain_lib.py find <query> [vault] [--limit N] [--body]
    uv run brain_lib.py log [--private] <op> <detail...>

The CLI needs the brain config (~/.config/brain/config.json, or the file named by
$BRAIN_CONFIG). Without one it exits with "Run /brain-init".
An explicit vault path overrides the configured roots for rebuild and find.
"""
from __future__ import annotations
import os, re, sys
import json
import datetime
from pathlib import Path

try:
    import yaml
except ImportError:
    sys.exit("pyyaml required. Run via uv so the script's own dependency block applies: uv run brain_lib.py ...")

CONFIG_PATH = Path(os.environ.get("BRAIN_CONFIG")
                   or Path.home() / ".config" / "brain" / "config.json").expanduser()


class ConfigError(Exception):
    pass


def load_config(path=None):
    p = Path(path) if path else CONFIG_PATH
    if not p.exists():
        return None
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, ValueError) as e:
        raise ConfigError(f"{p}: {e}") from e


def config_roots(cfg):
    out = []
    # privateVault is optional: a non-work root on its own remote, kept off the
    # work remotes of the other two.
    for key in ("personalVault", "sharedTree", "privateVault"):
        sec = (cfg or {}).get(key) or {}
        if sec.get("path"):
            out.append(Path(sec["path"]).expanduser())
    return out


def config_complete(cfg):
    if not cfg:
        return False
    # One root is enough. A solo vault configures only one of the three.
    return bool(config_roots(cfg) and cfg.get("journalsDir"))


# Frontmatter split: ---\n<yaml>\n---\n<body>, yaml.safe_load, dict-guard.
_FM_RE = re.compile(r"^---\s*\n(.*?)\n---\s*\n?(.*)$", re.S)


def split_frontmatter(text: str) -> tuple[dict, str]:
    if text.startswith("---"):
        m = _FM_RE.match(text)
        if m:
            try:
                fm = yaml.safe_load(m.group(1))
                if isinstance(fm, dict):
                    return fm, m.group(2)
            except Exception:
                pass
    return {}, text


NOT_CONFIGURED = "vault is not configured. Run /brain-init."


def _iter_roots(vault, roots):
    if roots is not None:
        return [Path(r) for r in roots]
    rs = config_roots(load_config())
    if not rs:
        raise ConfigError(NOT_CONFIGURED)
    return rs


# Non-wiki top-level trees per the vault schema (sources/ captures, digests/ recaps,
# attachments/ binaries). A root is a vault or vault-like directory that may contain
# these siblings alongside its wiki-* trees; never treat them as page trees, even
# when a source capture happens to carry a YAML-ish header that parses as a dict.
_NON_WIKI_TOP = {"sources", "digests", "attachments"}


def _scan_pages(vault, roots=None):
    """Yield (path, frontmatter, section_title) for every *.md with frontmatter
    under the configured roots. Section title = the top-level
    folder name within its root."""
    for root in _iter_roots(vault, roots):
        if not root.exists():
            continue
        for f in sorted(root.rglob("*.md")):
            if f.name in ("index.md", "MUSTKNOW.md", "log.md"):
                continue
            rel = f.relative_to(root)
            if rel.parts[0] in _NON_WIKI_TOP:
                continue
            fm, _body = split_frontmatter(f.read_text(encoding="utf-8", errors="replace"))
            if not isinstance(fm, dict) or not fm:
                continue
            title = rel.parts[0] if len(rel.parts) > 1 else root.name
            yield f, fm, title


def rebuild_index(vault: Path, roots=None) -> int:
    """Scan the wiki trees, rewrite vault/index.md, return total page count."""
    sections: dict[str, list[tuple[str, str]]] = {}
    total = 0
    for f, fm, title in _scan_pages(vault, roots):
        slug = f.stem
        summary = str(fm.get("summary", "")).strip()
        sections.setdefault(title, []).append((slug, summary))
        total += 1

    lines = [
        "# Wiki Index",
        "",
        "<!-- Generated by brain_lib.py rebuild. Do NOT hand-edit. Change a page and rebuild. -->",
        "",
        f"_{total} pages across {', '.join(sorted(sections))}._",
        "",
    ]
    for title in sorted(sections):
        lines.append(f"## {title}")
        for slug, summary in sorted(sections[title], key=lambda e: (e[0], e[1])):
            lines.append(f"- [[{slug}]] — {summary}")
        lines.append("")

    (vault / "index.md").write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    return total


MUSTKNOW_MAX_LINES = 30
MUSTKNOW_MAX_CHARS = 160


def load_topics(root: Path) -> dict[str, str]:
    """Read a root's topics.yaml, mapping folder path to a one-line gloss.
    Missing or unreadable means no glosses, which brain-lint reports."""
    f = root / "topics.yaml"
    if not f.exists():
        return {}
    try:
        data = yaml.safe_load(f.read_text(encoding="utf-8", errors="replace"))
    except Exception:
        return {}
    if not isinstance(data, dict):
        return {}
    return {str(k): str(v).strip() for k, v in data.items() if str(v).strip()}



def rebuild_mustknow(vault: Path, roots=None) -> int:
    """Rewrite each root's MUSTKNOW.md from pages carrying a `must_know:` line.

    These are the rules a session must apply unprompted, so they are injected in
    full rather than pointed at. Two admission tests, both narrow: if the session
    does not apply it without being asked the output is wrong, and one fact means
    one line. A corollary of an existing rule belongs in that page's body, not in
    a line of its own. must_know is a string or a list. Returns the line count."""
    scan_roots = _iter_roots(vault, roots)
    by_root: dict[Path, list[tuple[str, str]]] = {
        root: [] for root in scan_roots if root.exists()
    }
    for f, fm, _title in _scan_pages(vault, scan_roots):
        # A page may carry several distinct imperatives, so must_know is a string
        # or a list. Each entry is one rule: never bundle two facts into one line.
        raw = fm.get("must_know") or ""
        entries = raw if isinstance(raw, list) else [raw]
        rules = [str(r).strip() for r in entries if str(r).strip()]
        if not rules:
            continue
        for root in scan_roots:
            try:
                f.relative_to(root)
                break
            except ValueError:
                continue
        else:
            continue
        if root in by_root:
            by_root[root].extend((f.stem, r) for r in rules)

    total = 0
    for root, rules in by_root.items():
        path = root / "MUSTKNOW.md"
        if not rules:
            if path.exists():
                path.unlink()
            continue
        rules.sort()
        total += len(rules)
        lines = [
            f"# Must know — {root.name}",
            "",
            "Apply these without being asked. Read the cited page for the reasoning.",
            "",
        ]
        lines += [f"- {rule} [[{slug}]]" for slug, rule in rules]
        path.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")

    if total > MUSTKNOW_MAX_LINES:
        print(f"WARNING: {total} must_know lines exceeds the {MUSTKNOW_MAX_LINES} cap. "
              f"This block is injected into every session. Demote via /brain-digest.",
              file=sys.stderr)
    return total


def append_log(vault: Path, op: str, detail: str, private: bool = False) -> None:
    """Ensure vault/log.md starts with `# Operation Log`, then PREPEND (newest first,
    right under the header) an entry `## <ISO8601-UTC> — <OP> — <detail>`.

    private=True writes to the privateVault root, so an entry naming non-work
    pages never lands in a work repository. Without a privateVault it falls back
    to the personal root like any other entry."""
    cfg = load_config()
    roots = config_roots(cfg)
    if not roots:
        raise ConfigError(NOT_CONFIGURED)
    private_path = (cfg.get("privateVault") or {}).get("path")
    if private and private_path:
        log = Path(private_path).expanduser() / "log.md"
    else:
        log = roots[0] / "log.md"
    header = "# Operation Log"
    ts = datetime.datetime.now(datetime.timezone.utc).isoformat()
    entry = f"## {ts} — {str(op).upper()} — {detail}".rstrip()

    body = ""
    if log.exists():
        lines = log.read_text(encoding="utf-8", errors="replace").split("\n")
        while lines and lines[0].strip() == "":
            lines.pop(0)
        if lines and lines[0].strip() == header:
            lines.pop(0)
        body = "\n".join(lines).strip("\n")

    parts = [header, "", entry]
    if body:
        parts += ["", body]
    log.write_text("\n".join(parts) + "\n", encoding="utf-8")


# ---------------------------------------------------------------- CLI
def _resolve_vault(arg: str | None) -> Path:
    roots = config_roots(load_config())
    if not roots:
        raise ConfigError(NOT_CONFIGURED)
    if arg:
        return Path(arg).expanduser()
    return Path(os.path.commonpath([str(root) for root in roots]))


FIND_FIELDS = ("slug", "title", "summary", "tags")
STEM_SUFFIXES = ("ications", "ication", "ations", "ation", "ions", "ion", "ments", "ment",
                 "ings", "ing", "ies", "ied", "es", "ed", "ly", "s", "y", "e")
STEM_MIN = 4


def _stem(term: str) -> str:
    """Strip one common English suffix, keeping at least STEM_MIN letters.

    `verification` and `verify` both reduce to `verif`. The stem is matched as a
    substring, like the term itself, so it also finds the longer word forms."""
    for suffix in STEM_SUFFIXES:
        if term.endswith(suffix) and len(term) - len(suffix) >= STEM_MIN:
            return term[:-len(suffix)]
    return term


def find_pages(vault: Path, query: str, roots=None, limit: int = 20,
               search_body: bool = False) -> list[dict]:
    """Rank vault pages against a query, best match first.

    Matching is case-insensitive substring, and a multi-term query requires
    every term. A term matches a page field or the gloss that topics.yaml gives
    the page's folder. Three tiers rank the hits: exact words on the page, then
    word forms from _stem on the page, then hits that need the folder gloss.
    Inside a tier the first page field holding ALL the terms decides, so a slug
    hit beats a summary hit and terms spread across fields come after that.
    `pin: true` breaks a tie inside a band."""
    terms = [t for t in query.lower().split() if t]
    if not terms:
        return []
    scan_roots = _iter_roots(vault, roots)
    topics = {root: load_topics(root) for root in scan_roots}
    fields = FIND_FIELDS + (("body",) if search_body else ())
    passes = [[(t,) for t in terms]]
    stemmed = [(t, _stem(t)) for t in terms]
    if any(t != s for t, s in stemmed):
        passes.append(stemmed)
    matches: list[dict] = []
    for f, fm, _title in _scan_pages(vault, scan_roots):
        for root in scan_roots:
            try:
                rel = f.relative_to(root)
                break
            except ValueError:
                continue
        else:
            continue
        tags = fm.get("tags") or []
        if not isinstance(tags, list):
            tags = [tags]
        body = ""
        if search_body:
            _fm, body = split_frontmatter(f.read_text(encoding="utf-8", errors="replace"))
        # A key present but empty parses as None, and str(None) would make the
        # word "none" searchable, so every value is coerced through `or ""`.
        values = {
            "slug": f.stem,
            "title": str(fm.get("title") or ""),
            "summary": str(fm.get("summary") or ""),
            "tags": " ".join(str(t) for t in tags),
            "body": body,
            "topic": topics[root].get(rel.parent.as_posix(), ""),
        }
        low = {k: v.lower() for k, v in values.items()}

        def hit(k, alts):
            return any(a in low[k] for a in alts)

        def covered(forms, keys):
            return all(any(hit(k, alts) for k in keys) for alts in forms)

        rank = None
        for kind, forms in enumerate(passes):
            if covered(forms, fields):
                band = next((i for i, k in enumerate(fields)
                             if all(hit(k, alts) for alts in forms)), len(fields))
                rank = (kind, band, 0)
                break
        if rank is None:
            for kind, forms in enumerate(passes):
                if covered(forms, fields + ("topic",)):
                    on_page = any(hit(k, alts) for alts in forms for k in fields)
                    rank = (2, len(fields) if on_page else len(fields) + 1, kind)
                    break
        if rank is None:
            continue
        matches.append({
            "slug": f.stem,
            "root": root,
            "folder": rel.parent.as_posix(),
            "summary": values["summary"],
            "pinned": fm.get("pin") is True,
            "rank": rank,
        })
    matches.sort(key=lambda m: (m["rank"], 0 if m["pinned"] else 1, m["slug"]))
    return matches[:limit]


FIND_SUMMARY_CHARS = 100


def format_find(matches: list[dict], query: str) -> str:
    """Render ranked matches grouped under their folder gloss from topics.yaml."""
    if not matches:
        return (f'No match for "{query}". '
                f'Try fewer terms, or --body to search page text.\n')
    plural = "" if len(matches) == 1 else "es"
    lines = [f'{len(matches)} match{plural} for "{query}"', ""]
    groups: dict[tuple, list[dict]] = {}
    for m in matches:
        groups.setdefault((m["root"], m["folder"]), []).append(m)
    for (root, folder), items in groups.items():
        gloss = load_topics(root).get(folder, "")
        lines.append(f"{folder} \u2014 {gloss}" if gloss else folder)
        for m in items:
            lines.append(f"  {'*' if m['pinned'] else ' '} {m['slug']}")
            summary = m["summary"].strip()
            if summary:
                if len(summary) > FIND_SUMMARY_CHARS:
                    summary = summary[:FIND_SUMMARY_CHARS].rstrip() + "..."
                lines.append(f"      {summary}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str]) -> int:
    try:
        return _run(argv)
    except ConfigError as e:
        print(f"brain_lib: {e}", file=sys.stderr)
        return 1


def _run(argv: list[str]) -> int:
    if not argv:
        print("usage: brain_lib.py rebuild [vault] | find <query> [vault] | log [--private] <op> <detail...>", file=sys.stderr)
        return 2
    cmd = argv[0]

    if cmd == "rebuild":
        vault = _resolve_vault(argv[1] if len(argv) > 1 else None)
        n_index = rebuild_index(vault)
        n_must = rebuild_mustknow(vault)
        print(f"rebuilt  index={n_index} pages  "
              f"mustknow={n_must} lines  [{vault}]")
        return 0

    if cmd == "log":
        args = argv[1:]
        private = "--private" in args
        args = [a for a in args if a != "--private"]
        if len(args) < 2:
            print("usage: brain_lib.py log [--private] <op> <detail...>", file=sys.stderr)
            return 2
        vault = _resolve_vault(None)
        op, detail = args[0], " ".join(args[1:])
        append_log(vault, op, detail, private=private)
        print(f"logged  {op.upper()}  {detail}  [{vault}]")
        return 0

    if cmd == "find":
        args = argv[1:]
        search_body = "--body" in args
        args = [a for a in args if a != "--body"]
        limit = 20
        if "--limit" in args:
            i = args.index("--limit")
            if i + 1 >= len(args):
                print("usage: brain_lib.py find <query> [vault] [--limit N] [--body]",
                      file=sys.stderr)
                return 2
            limit = int(args[i + 1])
            del args[i:i + 2]
        if not args:
            print("usage: brain_lib.py find <query> [vault] [--limit N] [--body]",
                  file=sys.stderr)
            return 2
        query = args[0]
        # An explicit vault path wins over the configured roots. Without it the
        # search spans every configured root, which is what a session wants.
        explicit = args[1] if len(args) > 1 else None
        vault = _resolve_vault(explicit)
        roots = [vault] if explicit else None
        matches = find_pages(vault, query, roots=roots, limit=limit,
                             search_body=search_body)
        print(format_find(matches, query), end="")
        return 0

    print(f"unknown command: {cmd!r} (expected 'rebuild', 'find' or 'log')", file=sys.stderr)
    return 2


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
