import json, importlib.util, os, pathlib, plistlib, stat, subprocess, pytest
REAL_RUN = subprocess.run
here = pathlib.Path(__file__).parent.parent
spec = importlib.util.spec_from_file_location("brain_bootstrap", here / "scripts" / "brain_bootstrap.py")
bb = importlib.util.module_from_spec(spec); spec.loader.exec_module(bb)

def test_wire_settings_idempotent(tmp_path):
    s = tmp_path/"settings.json"
    s.write_text(json.dumps({"model":"opus","env":{"FOO":"bar"}}))
    bb.wire_settings("/v/path", settings=s)
    first = json.loads(s.read_text())
    assert first["env"]["CLAUDE_VAULT"] == "/v/path"
    assert first["env"]["FOO"] == "bar"            # preserved
    assert first["model"] == "opus"                # preserved
    assert first["autoMemoryEnabled"] is False
    bb.wire_settings("/v/path", settings=s)         # run twice
    assert json.loads(s.read_text()) == first       # no second-run change

def test_wire_settings_never_registers_a_hook(tmp_path):
    fresh = tmp_path/"fresh.json"
    bb.wire_settings("/v/path", settings=fresh)
    written = json.loads(fresh.read_text())
    assert written["env"]["CLAUDE_VAULT"] == "/v/path"
    assert written["autoMemoryEnabled"] is False
    assert "hooks" not in written                    # the plugin supplies the hook

    own = {"PreToolUse": [{"matcher": "Bash", "hooks": [{"type": "command", "command": "echo hi"}]}]}
    existing = tmp_path/"existing.json"
    existing.write_text(json.dumps({"hooks": own}))
    bb.wire_settings("/v/path", settings=existing)
    assert json.loads(existing.read_text())["hooks"] == own   # left untouched

def test_feed_rules_inserted_once(tmp_path):
    md = tmp_path/"CLAUDE.md"; md.write_text("# mine\n\nrule A\n")
    tpl = tmp_path/"feed.md"; tpl.write_text("JOURNAL at {JOURNALS}\n")
    assert bb.install_feed_rules(str(tmp_path/"journals"), claude_md=md, template=tpl) is True
    body = md.read_text()
    assert "brain-feed:start" in body and body.count("brain-feed:start") == 1
    assert "rule A" in body and str(tmp_path/"journals") in body
    assert bb.install_feed_rules(str(tmp_path/"journals"), claude_md=md, template=tpl) is False
    assert md.read_text().count("brain-feed:start") == 1  # still once

