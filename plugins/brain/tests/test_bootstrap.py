def test_scaffold_vault(tmp_path):
    v = tmp_path/"vault"
    tpl = tmp_path/"vault-CLAUDE.md"; tpl.write_text("SCHEMA\n")
    bb.scaffold_vault(v, ["wiki-me","life"], template=tpl)
