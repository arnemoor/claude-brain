def test_install_launchd_renders_template(tmp_path, monkeypatch):
    home = tmp_path/"home"
    agents = home/"Library"/"LaunchAgents"; agents.mkdir(parents=True)
    vault = tmp_path/"vault"
    log_dir = tmp_path/"logs"
    calls = []

    monkeypatch.setattr(bb.Path, "home", lambda: home)
    monkeypatch.setattr(bb, "CLAUDE_BIN", "/opt/test/bin/claude")
    monkeypatch.setattr(bb.shutil, "which", lambda _: "/opt/test/bin/claude")
    monkeypatch.setattr(bb.subprocess, "run", lambda args, **kwargs: calls.append(args))

    result = bb.install_launchd(vault_path=vault, log_dir=log_dir)
    dest = agents/"com.github.arnemoor.brain.vault-maintenance.plist"
    wrapper = log_dir/"brain-maintenance"
    rendered = dest.read_text()

    assert result == {"dest": dest, "wrapper": wrapper}
    assert log_dir.is_dir()
    assert wrapper.exists() and wrapper.stat().st_mode & stat.S_IXUSR
    wrapper_text = wrapper.read_text()
    assert "/opt/test/bin/claude" in wrapper_text
    assert "/brain-lint --fix" in wrapper_text and "/brain-digest" in wrapper_text
    assert 'config="${BRAIN_CONFIG:-${HOME}/.config/brain/config.json}"' in wrapper_text
    assert 'vault="${paths[1]}"' in wrapper_text
    assert str(vault) not in wrapper_text
    assert "explicit PATH" in wrapper_text
    assert "export BRAIN_NUDGE_OFF=1" in wrapper_text
    assert wrapper_text.index("export BRAIN_NUDGE_OFF=1") < wrapper_text.index("/brain-lint --fix")
    assert plistlib.loads(rendered.encode())["EnvironmentVariables"]["BRAIN_NUDGE_OFF"] == "1"
    assert str(vault) in rendered and str(log_dir) in rendered
    assert "com.github.arnemoor.brain.vault-maintenance" in rendered
    assert f"{home}/.local/bin" in rendered
    assert plistlib.loads(rendered.encode())["ProgramArguments"] == [str(wrapper)]
    for placeholder in ("{VAULT}", "{LOG_DIR}", "{LABEL}", "{HOME}", "{WRAPPER}"):
        assert placeholder not in rendered
    assert ["launchctl", "load", str(dest)] in calls

    second = bb.install_launchd(vault_path=vault, log_dir=log_dir)
    assert second == {"dest": dest, "wrapper": wrapper}
    assert wrapper.read_text() == wrapper_text and dest.read_text() == rendered

    with pytest.raises(ValueError, match="vault_path is required"):
        bb.install_launchd()


def test_install_launchd_rerun_refreshes_old_wrapper_and_reloads_agent(tmp_path, monkeypatch):
    home = tmp_path/"home"
    agents = home/"Library"/"LaunchAgents"; agents.mkdir(parents=True)
    vault = tmp_path/"vault"
    log_dir = tmp_path/"logs"; log_dir.mkdir()
    dest = agents/"com.github.arnemoor.brain.vault-maintenance.plist"
    wrapper = log_dir/"brain-maintenance"
    # An install from before 0.18.0: no BRAIN_NUDGE_OFF in wrapper or plist.
    wrapper.write_text("#!/bin/zsh\n# old wrapper\n")
    dest.write_text("<plist>old</plist>")
    calls = []
    monkeypatch.setattr(bb.Path, "home", lambda: home)
    monkeypatch.setattr(bb.shutil, "which", lambda _: "/opt/test/bin/claude")
    monkeypatch.setattr(bb.subprocess, "run", lambda args, **kwargs: calls.append(args))

    bb.install_launchd(vault_path=vault, log_dir=log_dir)

    assert "old wrapper" not in wrapper.read_text()
    assert "export BRAIN_NUDGE_OFF=1" in wrapper.read_text()
    assert plistlib.loads(dest.read_text().encode())["EnvironmentVariables"]["BRAIN_NUDGE_OFF"] == "1"
    # The running agent must pick up the new plist, so it is unloaded before and loaded after.
    assert calls == [["launchctl", "unload", str(dest)], ["launchctl", "load", str(dest)]]


def write_executable(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)
    path.chmod(0o755)


def install_wrapper(tmp_path, monkeypatch, solo=False):
    home = tmp_path / "home"
    (home / "Library" / "LaunchAgents").mkdir(parents=True)
    vault = tmp_path / "vault"
    personal, shared = vault / "personal", vault / "shared"
    personal.mkdir(parents=True)
    shared.mkdir()
    config = home / ".config" / "brain" / "config.json"
    config.parent.mkdir(parents=True)
    roots = ({"privateVault": {"path": str(vault)}} if solo else
             {"personalVault": {"path": str(personal)}, "sharedTree": {"path": str(shared)}})
    config.write_text(json.dumps(roots))
    calls = []
    monkeypatch.setattr(bb.Path, "home", lambda: home)
    monkeypatch.setattr(bb.shutil, "which", lambda _: "/missing/claude")
    monkeypatch.setattr(bb.subprocess, "run", lambda args, **kwargs: calls.append(args))
    wrapper = bb.install_launchd(vault_path=vault, log_dir=tmp_path / "logs")["wrapper"]
    return home, wrapper


def wrapper_environment(tmp_path, home, marker):
    binaries = tmp_path / "bin"
    write_executable(binaries / "claude", "#!/bin/sh\nexit 0\n")
    write_executable(binaries / "uv", "#!/bin/sh\nexit 0\n")
    env = os.environ.copy()
    env.update({"HOME": str(home), "PATH": f"{binaries}:/usr/bin:/bin", "MARKER": str(marker)})
    return env


def plugin_scripts(root, marker):
    scripts = root / "scripts"
    write_executable(scripts / "brain_git.sh", f"#!/bin/sh\nprintf '%s' {marker!r} > \"$MARKER\"\n")
    (scripts / "brain_lib.py").write_text("print('unused by uv stub')\n")


def test_launchd_wrapper_uses_runtime_plugin_resolution_and_prefers_marketplace(tmp_path, monkeypatch):
    home, wrapper = install_wrapper(tmp_path, monkeypatch)
    plugin_scripts(home / ".claude" / "plugins" / "marketplaces" / "claude-brain" / "plugins" / "brain", "stable")
    plugin_scripts(home / ".claude" / "plugins" / "cache" / "claude-brain" / "brain" / "9.9.9", "cache")
    text = wrapper.read_text()
    assert "marketplaces/claude-brain/plugins/brain" in text
    assert "cache/claude-brain/brain" in text
    assert "/0.8.0/scripts" not in text
    assert "brain/0." not in text
    marker = tmp_path / "selected"
    result = REAL_RUN([str(wrapper)], text=True, capture_output=True, env=wrapper_environment(tmp_path, home, marker))
    assert result.returncode == 0
    assert marker.read_text() == "stable"


def test_launchd_wrapper_selects_highest_cache_version_at_runtime(tmp_path, monkeypatch):
    home, wrapper = install_wrapper(tmp_path, monkeypatch)
    cache = home / ".claude" / "plugins" / "cache" / "claude-brain" / "brain"
    plugin_scripts(cache / "0.9.0", "old")
    plugin_scripts(cache / "0.10.0", "new")
    marker = tmp_path / "selected"
    result = REAL_RUN([str(wrapper)], text=True, capture_output=True, env=wrapper_environment(tmp_path, home, marker))
    assert result.returncode == 0
    assert marker.read_text() == "new"


def test_launchd_wrapper_fails_loudly_when_no_plugin_scripts_exist(tmp_path, monkeypatch):
    home, wrapper = install_wrapper(tmp_path, monkeypatch)
    marker = tmp_path / "selected"
    result = REAL_RUN([str(wrapper)], text=True, capture_output=True, env=wrapper_environment(tmp_path, home, marker))
    assert result.returncode != 0
    assert "plugin scripts are unavailable" in result.stderr


def test_launchd_wrapper_solo_vault_skips_the_shared_pull(tmp_path, monkeypatch):
    home, wrapper = install_wrapper(tmp_path, monkeypatch, solo=True)
    plugin_scripts(home / ".claude" / "plugins" / "marketplaces" / "claude-brain" / "plugins" / "brain", "pulled")
    marker = tmp_path / "selected"
    result = REAL_RUN([str(wrapper)], text=True, capture_output=True, env=wrapper_environment(tmp_path, home, marker))
    assert result.returncode == 0, result.stderr
    # brain_git.sh writes the marker. A solo vault has no shared tree, so it never runs.
    assert not marker.exists()
